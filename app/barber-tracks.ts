/** Active lyric index for a given playback time. */
export function activeLyricIndex(lines: LyricLine[], time: number): number {
  if (!lines.length) return -1;
  let active = 0;
  for (let i = 0; i < lines.length; i++) {
    if (lines[i].t <= time) active = i;
    else break;
  }
  return active;
}

/**
 * Stretch authored lyric timings across the real video duration so lines
 * advance with the audio from start to finish — not a fixed guess clock.
 */
export function scaleLinesToDuration(lines: LyricLine[], duration: number): LyricLine[] {
  if (!lines.length) return lines;
  if (!Number.isFinite(duration) || duration < 5) return lines;

  const maxT = Math.max(...lines.map((line) => line.t), 1);
  // Keep a short instrumental head, then spread lyrics through most of the song.
  const start = Math.min(8, duration * 0.06);
  const end = Math.max(start + 1, duration * 0.9);
  const span = end - start;

  return lines.map((line) => ({
    text: line.text,
    t: start + (line.t / maxT) * span,
  }));
}
